import pytest

from processing import filter_by_state, sort_by_date


@pytest.mark.parametrize(
    "data, state_value, expected",
    [
        (
            [
                {"id": 41428829, "state": "EXECUTED", "date": "2019-07-03T18:35:29.512364"},
                {"id": 594226727, "state": "CANCELED", "date": "2018-09-12T21:27:25.241689"},
            ],
            "EXECUTED",  # state_value теперь строка
            [{"id": 41428829, "state": "EXECUTED", "date": "2019-07-03T18:35:29.512364"}],
        ),
        (
            [{"id": 594226727, "state": "CANCELED", "date": "2018-09-12T21:27:25.241689"}],
            "EXECUTED",  # Нет совпадений
            [],
        ),
        (
            [
                {"id": 123, "date": "2023-10-27"},  # Нет ключа 'state'
                {"id": 456, "state": "EXECUTED", "date": "2023-10-27"},
            ],
            "EXECUTED",
            [{"id": 456, "state": "EXECUTED", "date": "2023-10-27"}],  # state есть только во втором
        ),
        ([], "EXECUTED", []),  # Пустой список
        ("not a list", "EXECUTED", []),  # Не список (должно обрабатываться)
        (
            [
                {"id": 789, "state": "EXECUTED", "date": "2023-10-28"},
                {"id": 910, "state": "EXECUTED", "date": "2023-10-29"},
            ],
            "EXECUTED",
            [
                {"id": 789, "state": "EXECUTED", "date": "2023-10-28"},
                {"id": 910, "state": "EXECUTED", "date": "2023-10-29"},
            ],  # Несколько совпадающих
        ),
        (
            [
                {"id": 111, "state": "PENDING", "date": "2023-10-30"},
                {"id": 222, "state": "CANCELED", "date": "2023-10-31"},
            ],
            "PENDING",
            [{"id": 111, "state": "PENDING", "date": "2023-10-30"}],  # Фильтруем по другому значению
        ),
    ],
)
def test_filter_by_state(data, state_value, expected):
    result = filter_by_state(data, state_value)
    assert result == expected


@pytest.mark.parametrize(
    "item, descending, expected",
    [
        (
            [
                {"id": 1, "date": "2023-10-29T10:00:00"},
                {"id": 2, "date": "2023-10-30T12:00:00"},
                {"id": 3, "date": "2023-10-28T14:00:00"},
            ],
            True,  # Сортировка по убыванию
            [
                {"id": 2, "date": "2023-10-30T12:00:00"},
                {"id": 1, "date": "2023-10-29T10:00:00"},
                {"id": 3, "date": "2023-10-28T14:00:00"},
            ],
        ),
        (
            [
                {"id": 1, "date": "2023-10-29T10:00:00"},
                {"id": 2, "date": "2023-10-30T12:00:00"},
                {"id": 3, "date": "2023-10-28T14:00:00"},
            ],
            False,  # Сортировка по возрастанию
            [
                {"id": 3, "date": "2023-10-28T14:00:00"},
                {"id": 1, "date": "2023-10-29T10:00:00"},
                {"id": 2, "date": "2023-10-30T12:00:00"},
            ],
        ),
        (
            [  # Некорректный формат даты
                {"id": 1, "date": "2023-10-29"},
                {"id": 2, "date": "2023-10-30T12:00:00"},
                {"id": 3, "date": "2023-10-28T14:00:00"},
            ],
            True,
            [
                {"id": 2, "date": "2023-10-30T12:00:00"},
                {"id": 1, "date": "2023-10-29"},
                {"id": 3, "date": "2023-10-28T14:00:00"},
            ],
        ),
        (
            [  # Нет ключа 'date'
                {"id": 1},
                {"id": 2, "date": "2023-10-30T12:00:00"},
                {"id": 3, "date": "2023-10-28T14:00:00"},
            ],
            True,
            [
                {"id": 2, "date": "2023-10-30T12:00:00"},
                {"id": 3, "date": "2023-10-28T14:00:00"},
            ],
        ),
        ([], True, []),  # Пустой список
        (
            [  # Одинаковые даты
                {"id": 1, "date": "2023-10-29T10:00:00"},
                {"id": 2, "date": "2023-10-29T10:00:00"},
                {"id": 3, "date": "2023-10-29T10:00:00"},
            ],
            True,
            [
                {"id": 1, "date": "2023-10-29T10:00:00"},
                {"id": 2, "date": "2023-10-29T10:00:00"},
                {"id": 3, "date": "2023-10-29T10:00:00"},
            ],
        ),
        (
            [  # С разными часовыми поясами
                {"id": 1, "date": "2023-11-05T10:00:00+03:00"},
                {"id": 2, "date": "2023-11-05T08:00:00+01:00"},
                {"id": 3, "date": "2023-11-05T05:00:00Z"},
            ],
            True,
            [
                {"id": 1, "date": "2023-11-05T10:00:00+03:00"},
                {"id": 2, "date": "2023-11-05T08:00:00+01:00"},
                {"id": 3, "date": "2023-11-05T05:00:00Z"},
            ],
        ),
        (
            [{"id": 1, "date": "2023-10-29T10:00:00"}, {"id": 2}, {"id": 3}],  # С датой в начале списка
            True,
            [
                {"id": 1, "date": "2023-10-29T10:00:00"},
            ],
        ),
        (
            [{"id": 1, "date": "2023-10-29T10:00:00"}],  # Только один элемент
            True,
            [{"id": 1, "date": "2023-10-29T10:00:00"}],
        ),
        (
            [  # Дата и не дата в перемешку
                {"id": 1, "date": "2023-10-29T10:00:00"},
                {"id": 2},
                {"id": 3, "date": "2023-10-27T10:00:00"},
                {"id": 4},
            ],
            True,
            [
                {"id": 1, "date": "2023-10-29T10:00:00"},
                {"id": 3, "date": "2023-10-27T10:00:00"},
            ],
        ),
    ],
)
def test_sort_by_date(item, descending, expected):
    result = sort_by_date(item, descending)
    assert result == expected
